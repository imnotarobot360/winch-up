checked as (
  select
    e.version,
    e.kind,
    e.ident,
    case e.kind
      when 'table'  then to_regclass(e.ident) is not null
      when 'index'  then to_regclass(e.ident) is not null
      when 'schema' then exists (select 1 from pg_namespace where nspname = e.ident)
      when 'type'   then exists (select 1 from pg_type t join pg_namespace n on n.oid = t.typnamespace
                                  where t.typname = e.ident and n.nspname in ('public', 'extensions', 'app'))
      when 'enumlabel' then exists (
        select 1 from pg_enum en join pg_type t on t.oid = en.enumtypid
         where t.typname = split_part(e.ident, ':', 1)
           and en.enumlabel = split_part(e.ident, ':', 2))
      when 'column' then exists (
        select 1 from information_schema.columns c
         where c.table_schema = split_part(split_part(e.ident, ':', 1), '.', 1)
           and c.table_name   = split_part(split_part(e.ident, ':', 1), '.', 2)
           and c.column_name  = split_part(e.ident, ':', 2))
      when 'trigger' then exists (select 1 from pg_trigger where tgname = e.ident and not tgisinternal)
      when 'policy'  then exists (select 1 from pg_policies where policyname = e.ident)
    end as present
  from expected e
