create or replace function app.miles_to_meters(p_miles numeric)
returns double precision
language sql
immutable
parallel safe
as $$ select (p_miles * 1609.344)::double precision; $$;

-- Deterministic ~0.5-1 mile offset used for the public board.
-- Deterministic on purpose: the blurred pin must not jitter between page loads, because a moving
-- pin would let anyone average several samples back to the real location.
create or replace function app.blur_point(p_point extensions.geography, p_seed uuid)
returns extensions.geography
language sql
immutable
parallel safe
set search_path = public, extensions, pg_temp
as $$
  select extensions.st_project(
    p_point,
    -- 800 m .. 1700 m
    (800 + (('x' || substr(md5(p_seed::text), 1, 7))::bit(28)::int % 900))::double precision,
    radians((('x' || substr(md5(p_seed::text), 9, 7))::bit(28)::int % 360)::double precision)
  );
$$;

comment on function app.blur_point(extensions.geography, uuid) is
  'Stable ~1 mile offset for public display. Never expose the exact point before acceptance.';

