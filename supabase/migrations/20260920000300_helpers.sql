-- Hard requirements only. Anything softer belongs in ranking, not filtering: over-constraining
-- the candidate pool is how a stuck driver ends up with zero volunteers.
create or replace function app.required_equipment(
  p_needs_tractor boolean,
  p_needs_second_truck boolean,
  p_stuck_type stuck_type,
  p_stuck_depth stuck_depth
)
returns equipment_type[]
language sql
immutable
parallel safe
set search_path = public, extensions, pg_temp
as $$
  select coalesce(array_agg(e), '{}'::equipment_type[])
  from (
    select 'tractor'::equipment_type      where coalesce(p_needs_tractor, false)
    union all
    select 'second_truck'::equipment_type where coalesce(p_needs_second_truck, false)
  ) as t(e);
$$;

