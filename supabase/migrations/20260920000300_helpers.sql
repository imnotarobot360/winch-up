-- ---------------------------------------------------------------------------
-- Rate limiting
-- ---------------------------------------------------------------------------

-- Returns true when the caller is allowed to proceed, and records the hit.
-- Callers pass a namespaced key, e.g. 'request:phone:+12815550123' or 'request:ip:203.0.113.4'.
create or replace function app.check_rate_limit(p_key text, p_max integer, p_window interval)
returns boolean
language plpgsql
volatile
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  hits integer;
begin
  delete from public.rate_limit_hits
   where created_at < now() - interval '24 hours';

  select count(*) into hits
    from public.rate_limit_hits
   where bucket_key = p_key
     and created_at > now() - p_window;

  if hits >= p_max then
    return false;
  end if;

  insert into public.rate_limit_hits (bucket_key) values (p_key);
  return true;
end;
$$;

